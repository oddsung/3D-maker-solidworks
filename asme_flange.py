"""
asme_flange.py - ASME 플랜지 표준 치수 (Class 300)

출처 (ASME CODE 2025 폴더의 PDF 에서 옮김, 단위 mm / 볼트·구멍 지름은 inch 를 mm 로 환산):
  - ASME B16.5-2025  Table 10 (Class 300 드릴링 템플릿: O, W 볼트 원, 구멍 지름, 볼트 수, 볼트 지름) p.151
                     Table 11 (Class 300 플랜지 치수: t_f 두께, X 허브 지름, A 목 지름, Y 길이) p.153~154
  - ASME B16.47-2025 Table 33 (Class 300 Series A, NPS 26~60) p.73~74
                     Table 39 (Class 300 Series B, NPS 26~60) p.97~98

담당자 규칙: NPS 24 까지는 B16.5, 26 부터는 B16.47. B16.47 은 Series A(두꺼움) / B(얇음, 일반적) —
기본은 Series B, 도면 부품표에 'SERIES A' 가 있으면 A.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Optional

INCH = 25.4


@dataclass(frozen=True)
class FlangeData:
    std: str            # "B16.5" | "B16.47A" | "B16.47B"
    nps: float
    od: float           # O, 플랜지 외경
    thickness: float    # t_f, 플랜지 두께 (RF 1.6 제외)
    bolt_circle: float  # W (B16.5) / R.. 볼트 원 지름
    n_bolts: int
    hole_d: float       # 볼트 구멍 지름 (mm)
    bolt_d: float       # 볼트 지름 (mm)
    hub_x: float        # X, 허브 바닥 지름
    neck_a: float       # A, 용접 목 지름 (파이프 외경)
    length_y: float     # Y, 용접 목 플랜지 전체 길이
    raised_face_d: float = 0.0
    source: str = ""
    blind_t: float = 0.0  # 블라인드 플랜지 두께 (B16.5 는 t_f 와 같음, B16.47 은 별도 열)


def _in(v: float) -> float:
    return round(v * INCH, 2)


