def choose_standard(nps: float, series_hint: str = "") -> str:
    """담당자 규칙: 24" 까지 B16.5, 26" 부터 B16.47 (기본 Series B, 'A' 표기가 있으면 A)"""
    if nps <= 24:
        return "B16.5"
    return "B16.47A" if series_hint.upper().strip() == "A" else "B16.47B"


def flange_cl300(nps: float, series_hint: str = "") -> Optional[FlangeData]:
    std = choose_standard(nps, series_hint)
    if std == "B16.5":
        row = _B165_CL300.get(float(nps))
        if not row:
            return None
        O, W, hole, n, bolt, tf, X, A, Y, rf = row
        return FlangeData(std, nps, O, tf, W, n, _in(hole), _in(bolt), X, A, Y, rf,
                          "ASME B16.5-2025 Table 10/11 (Class 300)", tf)
    table = _B1647A_CL300 if std == "B16.47A" else _B1647B_CL300
    row = table.get(int(nps))
    if not row:
        return None
    O, tf, Y, X, A, rf, bc, n, hole, bolt = row
    blind = (_B1647A_BLIND if std == "B16.47A" else _B1647B_BLIND).get(int(nps), tf)
    return FlangeData(std, nps, O, tf, bc, n, _in(hole), _in(bolt), X, A, Y, rf,
                      f"ASME B16.47-2025 Table {'33' if std.endswith('A') else '39'} (Class 300 Series {std[-1]})", blind)


def describe(fd: FlangeData) -> str:
    return (f"{fd.std} CL300 {fd.nps:g}\": OD {fd.od:g}, B.C {fd.bolt_circle:g}, "
            f"{fd.n_bolts}-Ø{fd.hole_d:g} 구멍 (볼트 {fd.bolt_d:g}), t {fd.thickness:g}")


